"""Head to head: bt-audit vs overfit-gauntlet (MIT, PyPI 0.1.0) on the same inputs.

Run it with both installed in one environment (benchmarks/run_vs_overfit_gauntlet.sh does that):

    python benchmarks/vs_overfit_gauntlet.py [--runs 40] [--freqtrade path/to/freqtrade-strategies]

Three cases, each repeated over seeds so neither tool is judged on one lucky draw:

1. Cherry-picked noise: 50 zero-edge variants, T = 1,500 daily periods; the best in-sample one is
   graded and each tool is told 50 variants were tried. A tool should not pass it.
2. Planted edge: one variant with per-period Sharpe 0.12 (about 1.9 annualised) among 10,
   T = 2,000. A tool should pass it.
3. Lookahead: the freqtrade-strategies folder its maintainers labelled as leaking the future
   (positives) and the other strategy files (negatives), through each tool's linter.

"Pass" means bt-audit's overall grade PASS and overfit-gauntlet's verdict VALIDATED: each tool's
own top grade. Both tools' own numbers are reported, including where overfit-gauntlet does better.
Writes examples/VS-OVERFIT-GAUNTLET.md.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import numpy as np

from bt_audit.lookahead import scan
from bt_audit.report import run_audit

ROOT = Path(__file__).resolve().parent.parent
FREQTRADE = "https://github.com/freqtrade/freqtrade-strategies"


def gauntlet():
    try:
        import overfit_gauntlet as og
    except ImportError:
        sys.exit("overfit-gauntlet is not installed: run benchmarks/run_vs_overfit_gauntlet.sh")
    return og


def verdict_name(v) -> str:
    return getattr(v, "name", str(v)).split(".")[-1].upper()


def noise_case(rng, t=1500, n=50):
    x = rng.normal(0, 0.01, (t, n))
    best = int((x.mean(0) / x.std(0)).argmax())
    return x[:, best], x


def edge_case(rng, t=2000, n=10):
    x = rng.normal(0, 0.01, (t, n))
    x[:, 3] += 0.0012
    return x[:, 3], x


def grade_both(og, series, trials):
    t0 = time.perf_counter()
    a = run_audit(series, trials, n_trials=trials.shape[1])
    t1 = time.perf_counter()
    rep = og.run_gauntlet(series, ann=252, n_trials=trials.shape[1])
    t2 = time.perf_counter()
    checks = {c.name: c.verdict for c in a.checks}
    return a.grade, verdict_name(rep.verdict), checks, t1 - t0, t2 - t1


def returns_cases(og, runs):
    out = {}
    for label, make, seed in (("cherry-picked noise (best of 50)", noise_case, 100),
                              ("planted edge (SR 0.12 per period among 10)", edge_case, 200)):
        rng = np.random.default_rng(seed)
        bt, gv, sel, tb, tg = [], [], {"Selection bias (Deflated Sharpe)": 0, "Selection bias (Hansen SPA)": 0}, 0.0, 0.0
        for _ in range(runs):
            series, trials = make(rng)
            g, v, checks, dtb, dtg = grade_both(og, series, trials)
            bt.append(g)
            gv.append(v)
            for k in sel:
                sel[k] += checks.get(k) == "PASS"
            tb += dtb
            tg += dtg
        out[label] = {
            "bt_pass": sum(g == "PASS" for g in bt) / runs,
            "bt_not_fail": sum(g != "FAIL" for g in bt) / runs,
            "og_validated": sum(v == "VALIDATED" for v in gv) / runs,
            "og_weak": sum(v == "WEAK" for v in gv) / runs,
            "dsr_pass": sel["Selection bias (Deflated Sharpe)"] / runs,
            "spa_pass": sel["Selection bias (Hansen SPA)"] / runs,
            "sec_bt": tb / runs,
            "sec_og": tg / runs,
        }
    return out


def lint_case(root: Path):
    strategies = root / "user_data" / "strategies"
    labelled = strategies / "lookahead_bias"
    pos = sorted(labelled.glob("*.py"))
    neg = sorted(p for p in strategies.rglob("*.py") if labelled not in p.parents)
    bt_hits = {Path(f.file).name for f in scan(labelled) if f.confidence in ("high", "medium")}
    bt_neg = {f.file for f in scan(strategies) if f.confidence in ("high", "medium")
              and "lookahead_bias" not in str(f.file)}

    def og_flags(p: Path) -> bool:
        r = subprocess.run(["gauntlet", "lint", str(p)], capture_output=True, text=True)
        return r.returncode != 0

    og_pos = sum(og_flags(p) for p in pos)
    og_neg = sum(og_flags(p) for p in neg)
    return {
        "positives": len(pos), "negatives": len(neg),
        "bt_caught": sum(p.name in bt_hits for p in pos), "bt_false": len(bt_neg),
        "og_caught": og_pos, "og_false": og_neg,
    }


def write_md(res, lint, runs, og_version):
    L = ["# bt-audit vs overfit-gauntlet", "",
         f"Generated by `benchmarks/vs_overfit_gauntlet.py` with overfit-gauntlet {og_version}, {runs} seeded runs per "
         "returns case. Pass means each tool's own top grade: bt-audit PASS, overfit-gauntlet VALIDATED.", "",
         "## Returns", "",
         "| Case | bt-audit PASS | bt-audit not FAIL | overfit-gauntlet VALIDATED | overfit-gauntlet WEAK | "
         "bt-audit DSR PASS | bt-audit SPA PASS | seconds per run (bt / og) |",
         "|---|---|---|---|---|---|---|---|"]
    for k, r in res.items():
        L.append(f"| {k} | {r['bt_pass']:.0%} | {r['bt_not_fail']:.0%} | {r['og_validated']:.0%} | {r['og_weak']:.0%} | "
                 f"{r['dsr_pass']:.0%} | {r['spa_pass']:.0%} | {r['sec_bt']:.1f} / {r['sec_og']:.1f} |")
    L += ["", "On cherry-picked noise a lower pass rate is better; on the planted edge a higher one is. bt-audit's "
          "overall grade is its weakest check, so a true edge can still miss PASS on costs or sizing; the DSR and SPA "
          "columns isolate the selection-bias checks.", ""]
    if lint:
        L += ["## Lookahead linters on freqtrade-strategies", "",
              "| | labelled leaky files caught | other strategy files flagged |", "|---|---|---|",
              f"| bt-audit (medium or high confidence) | {lint['bt_caught']} of {lint['positives']} | "
              f"{lint['bt_false']} of {lint['negatives']} |",
              f"| overfit-gauntlet (`gauntlet lint` exit code) | {lint['og_caught']} of {lint['positives']} | "
              f"{lint['og_false']} of {lint['negatives']} |", "",
              "bt-audit's min-max rule was written after reading the labelled set, so its recall here is not held out. "
              "An unlabelled file being flagged is not proof of a false positive; it is a file to read.", ""]
    (ROOT / "examples" / "VS-OVERFIT-GAUNTLET.md").write_text("\n".join(L))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=int, default=40)
    ap.add_argument("--freqtrade", help="existing clone of freqtrade-strategies (default: clone to a temp dir)")
    ap.add_argument("--skip-lint", action="store_true")
    a = ap.parse_args()
    og = gauntlet()
    try:
        from importlib.metadata import version
        og_version = version("overfit-gauntlet")
    except Exception:
        og_version = "unknown"
    res = returns_cases(og, a.runs)
    lint = None
    if not a.skip_lint:
        root = Path(a.freqtrade) if a.freqtrade else Path(tempfile.mkdtemp()) / "freqtrade-strategies"
        if not a.freqtrade:
            subprocess.run(["git", "clone", "-q", "--depth", "1", FREQTRADE, str(root)], check=True)
        lint = lint_case(root)
    write_md(res, lint, a.runs, og_version)
    print((ROOT / "examples" / "VS-OVERFIT-GAUNTLET.md").read_text())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
